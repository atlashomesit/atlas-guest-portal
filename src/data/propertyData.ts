export const propertyImages: Record<string, string[]> = Object.fromEntries(
    Object.entries(propertyImagePaths).map(([key, paths]) => [
        key,
        paths.map(path => {
            // If the path is already a full URL, return it as is
            if (path.startsWith('http')) {
                return path;
            }
            // If the path starts with a number (like '101/'), assume it's a property folder
            if (/^\d+\//.test(path)) {
                return `https://atlashomestorage.blob.core.windows.net/listing-images/${path}`;
            }
            // Default case
            return `https://atlashomestorage.blob.core.windows.net/listing-images/${key}/${path}`;
        })
    ])
);

